#%%
# ─── Section 5: Fit RECAST's ETAS model — temporal NLL baseline ───────────────
#
# Before training RecurrentTPP we fit RECAST's built-in parametric ETAS model
# to the same training sequences.  This gives us:
#   (a) A BASELINE NLL that RecurrentTPP should eventually beat (or match).
#   (b) A PARAMETER RECOVERY check: do the fitted p, c, alpha, mu match the
#       true values used in data generation?
#
# IMPORTANT NLL CAVEAT:
#   ETAS(use_spatial=False).nll_loss() returns only the TEMPORAL NLL per day
#   (log-intensity of inter-event times + compensator integral).
#   RecurrentTPP.nll_loss() returns TEMPORAL + 0.1×SPATIAL + MAGNITUDE NLL.
#   These are NOT identical quantities, so the numerical comparison is
#   approximate.  The magnitude term is the same GR distribution for both, but
#   ETAS scores it analytically (as part of the compensator) while RecurrentTPP
#   scores it via the GR hypernet.  The 0.1 weight on the spatial term keeps
#   the temporal component dominant in RECAST's NLL.
#
# We use use_spatial=False here to isolate the temporal component and keep the
# comparison as direct as possible.  (The spatial ETAS — use_spatial=True —
# was implemented in eq/models/etas.py but is a separate experiment.)

etas_baseline = ETAS(
    mag_completeness         = MC,
    richter_b                = 1.0,
    use_spatial              = False,   # temporal-only; see caveat above
    # Initialise near the true values so the optimizer doesn't wander far.
    # This is not necessary but speeds up convergence.
    omori_p_init             = TRUE_P,
    omori_c_init             = TRUE_C,
    productivity_alpha_init  = TRUE_ALPHA,
    base_rate_init           = max(TRUE_MU, 0.01),   # must be > 0 for log-space init
    report_params            = False,
    learning_rate            = 5e-2,
)

# ── Manual training loop (no Lightning) ────────────────────────────────────────
# Full-batch gradient descent: all training sequences in one batch.
# This is fine because N_train ≈ 180 sequences × 30 days is small.
train_batch_etas = eq.data.Batch.from_list(train_seqs)
etas_optimizer   = torch.optim.Adam(etas_baseline.parameters(), lr=5e-2)

ETAS_EPOCHS = 600
etas_losses = []

print(f"Training ETAS baseline for {ETAS_EPOCHS} epochs...")
etas_baseline.train()
for epoch in range(ETAS_EPOCHS):
    etas_optimizer.zero_grad()
    # nll_loss returns one scalar per sequence; we average across the batch.
    nll = etas_baseline.nll_loss(train_batch_etas).mean()
    nll.backward()
    # Gradient clipping prevents log-space parameters from exploding early on.
    torch.nn.utils.clip_grad_norm_(etas_baseline.parameters(), 1.0)
    etas_optimizer.step()
    etas_losses.append(nll.item())

    if (epoch + 1) % 100 == 0:
        print(f"  Epoch {epoch+1:4d}  NLL={nll.item():.4f}  "
              f"p={etas_baseline.p.item():.3f}  "
              f"c={etas_baseline.c.item():.5f}  "
              f"mu={etas_baseline.mu.item():.4f}  "
              f"alpha={etas_baseline.alpha.item():.3f}")

etas_baseline.eval()

fig, ax = plt.subplots(figsize=(8, 3))
ax.plot(etas_losses, linewidth=0.8, color='darkorange')
ax.set_xlabel("Epoch")
ax.set_ylabel("Mean NLL / day")
ax.set_title("ETAS baseline training loss")
plt.tight_layout()
plt.savefig(f"{FIGS_DIR}/etas_training_loss.png", dpi=150, bbox_inches='tight')
plt.show()

