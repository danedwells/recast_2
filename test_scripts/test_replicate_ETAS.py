# ─── Section 3: Normalization statistics ───────────────────────────────────────
# RecurrentTPP encodes events as:
#   time  → log(τ) − log(τ_mean)          (log inter-time, zero-centred)
#   space → (x − x_mean) / x_std,  same for y
#   mag   → (m − Mc)                       (no normalisation needed; already ≥ 0)
#
# We compute τ_mean, x_mean, x_std, y_mean, y_std from the TRAINING set only
# and register them as fixed buffers in the model.  Applying them to val/test
# sequences is valid because ETAS is stationary: the population statistics are
# the same everywhere in the box and across all time windows.
#
# Unlike test_case_study.py we do NOT inflate the std by a jitter term because
# we apply no spatial jitter here (explained in Section 5 below).

