#%%
# ─── Section 6: Define and train RecurrentTPP ─────────────────────────────────
#
# Architecture (from eq/models/recurrent.py):
#   Encoder: each event → [log(τ) − log(τ_mean), (x−x_mean)/x_std,
#                           (y−y_mean)/y_std, (m−Mc)]  — a 4-dimensional vector
#   RNN (GRU): encodes event history → context vector of size context_size
#   Decoders (hypernets):
#     hypernet_time → Weibull mixture parameters (num_components_time components)
#     hypernet_xy   → 2D Gaussian mixture parameters with Cholesky covariance
#     hypernet_mag  → Gutenberg-Richter parameters (effectively learns b-value)
#
# NLL loss returned per sequence per day:
#   − [log p(inter_times) + 0.1 × log p(x_loc, y_loc) + log S(t_last)
#      − log S(t_first)  − log p(magnitudes)]  /  (t_end − t_nll_start)
#
# The 0.1 spatial weight means the model is primarily a temporal forecaster;
# spatial structure is a secondary objective.
#
# MODEL SIZE: We use a smaller model than test_case_study.py (context_size=64
# vs 256) because the synthetic sequences are shorter (30 vs 365 days) and
# the ETAS dynamics are simpler than real multi-sequence global seismicity.

model = eq.models.RecurrentTPP(
    context_size         = 64,    # RNN hidden-state dimension
    num_components_time  = 8,     # Weibull mixture components for time
    num_components_space = 16,    # Gaussian mixture components for space
    tau_mean             = tau_mean,
    x_mean               = x_mean,
    y_mean               = y_mean,
    x_std                = x_std,
    y_std                = y_std,
)
print(f"RecurrentTPP parameters: {sum(p.numel() for p in model.parameters()):,}")

# ── Training configuration ──────────────────────────────────────────────────────
_RETRAIN_   = True   # set False to skip training and just load the saved checkpoint
EPOCHS      = 300
BATCH_SIZE  = 32

# SPATIAL JITTER NOTE:
#   test_case_study.py applies random spatial translation per sequence during
#   training (collate_with_jitter).  This prevents the model from memorising
#   the mainshock's absolute position (always at origin) as a spatial prior.
#
#   We do NOT apply jitter here because:
#   (a) There is no mainshock — events are scattered across the box uniformly.
#   (b) The ETAS background is spatially uniform; the model should NOT need to
#       learn any preferred absolute location.
#   (c) Adding jitter would widen the apparent spatial distribution and inflate
#       x_std / y_std beyond the true box extent, making normalization wrong.
#
#   Plain Batch.from_list() is therefore the correct collate function.

if _RETRAIN_:
    device    = 'cuda' if torch.cuda.is_available() else 'cpu'
    model     = model.to(device)
    print(f"Training RecurrentTPP on: {device}")

    optimizer    = torch.optim.Adam(model.parameters(), lr=5e-4)
    scheduler    = CosineAnnealingLR(optimizer, T_max=EPOCHS)
    train_loader = DataLoader(
        train_ds,
        batch_size  = BATCH_SIZE,
        shuffle     = True,
        collate_fn  = eq.data.Batch.from_list,   # no jitter (see note above)
    )
    val_batch = eq.data.Batch.from_list(val_seqs).to(device)

    train_losses, val_losses = [], []
    model.train()
    for epoch in range(EPOCHS):
        epoch_losses = []
        for batch in train_loader:
            batch = batch.to(device)
            optimizer.zero_grad()
            nll = model.nll_loss(batch).mean()
            nll.backward()
            # Clip gradients to prevent parameter explosions (especially early on
            # when the context vectors are near-random and spatial NLL can spike).
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            epoch_losses.append(nll.item())

        # Validation NLL — computed without gradients on the full validation set.
        with torch.no_grad():
            v_nll = model.nll_loss(val_batch).mean().item()

        epoch_mean = float(np.mean(epoch_losses))
        train_losses.append(epoch_mean)
        val_losses.append(v_nll)
        scheduler.step()

        if (epoch + 1) % 25 == 0:
            print(f"Epoch {epoch+1:3d}  train={epoch_mean:.4f}  val={v_nll:.4f}")

    torch.save(model.state_dict(), f"{SAVE_DIR}/recast_etas2.pt")

    fig, ax = plt.subplots(figsize=(9, 3))
    ax.plot(train_losses, label='train', color='steelblue', lw=0.9)
    ax.plot(val_losses,   label='val',   color='orange',    lw=0.9)
    ax.axhline(etas_test_nll, ls='--', color='red', lw=1.2, label='ETAS temporal NLL')
    ax.set_xlabel("Epoch")
    ax.set_ylabel("Mean NLL / day")
    ax.set_title("RecurrentTPP training loss  (dashed = ETAS temporal baseline)")
    ax.legend()
    plt.tight_layout()
    plt.savefig(f"{FIGS_DIR}/recast_training_loss.png", dpi=150, bbox_inches='tight')
    plt.show()


