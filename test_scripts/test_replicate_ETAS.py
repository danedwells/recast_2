def forecast_cumulative(batch, t_cut, t_grid):
    """Cumulative event count relative to t_cut for each sampled trajectory.

    Args:
        batch   : Batch of sampled sequences from model.sample().
        t_cut   : The conditioning cutoff time (events before this are history).
        t_grid  : 1-D array of times at which to evaluate the cumulative count.

    Returns:
        cum: int array of shape (batch_size, len(t_grid)).
             cum[i, j] = number of events in trajectory i with arrival_time
             in (t_cut, t_cut + t_grid[j]].
    """
    cum = np.zeros((batch.batch_size, len(t_grid)), dtype=int)
    for i in range(batch.batch_size):
        mask      = batch.mask[i].bool()
        times     = batch.arrival_times[i][~mask].numpy()
        # Only count events strictly after the conditioning cutoff
        fore_rel  = np.sort(times[times > t_cut] - t_cut)
        cum[i]    = np.searchsorted(fore_rel, t_grid, side='right')
    return cum


