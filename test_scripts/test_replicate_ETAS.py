# ─── Section 13: Data quantity sweep ──────────────────────────────────────────
# Key research question: how much data does RecurrentTPP need to match ETAS?
#
# For each N in N_TRAIN_SIZES we:
#   1. Take the first N sequences from the training set.
#   2. Train a fresh RecurrentTPP for SWEEP_EPOCHS epochs.
#   3. Evaluate its NLL on the full test set.
#
# The ETAS baseline NLL (from Section 5) is shown as a dashed horizontal line.
# When the RECAST curve crosses below this line, RECAST has exceeded the
# parametric model's predictive accuracy.
#
# NOTE: SWEEP_EPOCHS is intentionally short (50 epochs) so each point can be
# trained in seconds.  The NLLs therefore reflect early-convergence performance,
# not the fully-trained model.  Increase SWEEP_EPOCHS for a more accurate sweep
# at the cost of longer runtime.

N_TRAIN_SIZES = [5, 10, 25, 50, 100, len(train_seqs)]
SWEEP_EPOCHS  = 50

sweep_nlls = []
print(f"\nData quantity sweep  ({len(N_TRAIN_SIZES)} points × {SWEEP_EPOCHS} epochs each)")

for n_train in N_TRAIN_SIZES:
    # Fresh model with the same architecture every time (no warm-start)
    m_sweep = eq.models.RecurrentTPP(
        context_size         = 64,
        num_components_time  = 8,
        num_components_space = 16,
        tau_mean             = tau_mean,
        x_mean               = x_mean,
        y_mean               = y_mean,
        x_std                = x_std,
        y_std                = y_std,
    )
    opt_sweep = torch.optim.Adam(m_sweep.parameters(), lr=5e-4)

    # Build a DataLoader from the first n_train sequences
    subset_ds     = eq.data.InMemoryDataset(train_seqs[:n_train])
    loader_sweep  = DataLoader(
        subset_ds,
        batch_size = min(32, n_train),    # smaller batch when n_train is tiny
        shuffle    = True,
        collate_fn = eq.data.Batch.from_list,
    )

    m_sweep.train()
    for _ in range(SWEEP_EPOCHS):
        for batch in loader_sweep:
            opt_sweep.zero_grad()
            model.nll_loss(batch).mean().backward() if False else \
            m_sweep.nll_loss(batch).mean().backward()
            torch.nn.utils.clip_grad_norm_(m_sweep.parameters(), 1.0)
            opt_sweep.step()

    m_sweep.eval()
    with torch.no_grad():
        nll_sweep = m_sweep.nll_loss(test_batch).mean().item()
    sweep_nlls.append(nll_sweep)
    print(f"  N_train={n_train:4d}  test NLL={nll_sweep:.4f}")

# ── Plot ────────────────────────────────────────────────────────────────────────
fig, ax = plt.subplots(figsize=(7, 4))
ax.semilogx(N_TRAIN_SIZES, sweep_nlls, 'o-', color='steelblue',
            linewidth=1.5, markersize=6, label='RecurrentTPP')
ax.axhline(etas_test_nll, ls='--', color='darkorange', lw=1.5,
           label=f'ETAS baseline  ({etas_test_nll:.4f})')
ax.set_xlabel("Number of training sequences  (log scale)")
ax.set_ylabel("Test NLL / day")
ax.set_title(f"Data quantity sweep  ({SWEEP_EPOCHS} epochs each)\n"
             "How much data does RECAST need to match ETAS?")
ax.legend()
plt.tight_layout()
plt.savefig(f"{FIGS_DIR}/data_quantity_sweep.png", dpi=150, bbox_inches='tight')
plt.show()

print(f"\nETAS baseline NLL : {etas_test_nll:.4f}")
print(f"RECAST (full data): {sweep_nlls[-1]:.4f}")
crossover = [n for n, nll in zip(N_TRAIN_SIZES, sweep_nlls) if nll <= etas_test_nll]
if crossover:
    print(f"RECAST first beats ETAS at N_train ≥ {crossover[0]}")
else:
    print("RECAST does not yet beat ETAS with these training sizes / epoch budget.")
    print("Try increasing SWEEP_EPOCHS or N_CATALOGS in generate_etas_synthetic.py.")

