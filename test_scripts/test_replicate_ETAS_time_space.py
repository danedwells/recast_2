    _cat_df = pd.DataFrame(rows).sort_values('time').reset_index(drop=True)
    total_cat_days = _N_SYN * (float(T_DAYS) + _SEQ_GAP_DAYS)
    t_inv_start = T_REF
    t_inv_end   = T_REF + dt.timedelta(days=total_cat_days)
    print(f"  Catalog: {len(_cat_df)} events over {total_cat_days:.0f} days")

    # ── 3. Run etas_2 inversion ───────────────────────────────────────────────
    _shape_coords = [
        [LAT_MIN, LON_MIN], [LAT_MAX, LON_MIN],
        [LAT_MAX, LON_MAX], [LAT_MIN, LON_MAX],
    ]
    _inv_meta = {
        'catalog':               _cat_df,
        'auxiliary_start':       t_inv_start,   # no auxiliary events
        'timewindow_start':      t_inv_start,
        'timewindow_end':        t_inv_end,
        'mc':                    MC,
        'delta_m':               0.1,
        'coppersmith_multiplier': 100,
        'shape_coords':          _shape_coords,
        'theta_0':               TRUE_PARAMS,   # warm start: converges faster
    }
    print("Running etas_2 inversion (may take a few minutes) …")
    _calc = ETASParameterCalculation(_inv_meta)
    _calc.prepare()
    _recovered = _calc.invert()

    with open(_RECOVERY_JSON, 'w') as _f:
        import json as _json
        # Convert numpy scalars to Python floats for JSON serialisation
        _json.dump({'recovered': {k: (float(v) if v is not None else None)
                                  for k, v in _recovered.items()},
                    'n_events': len(_cat_df),
                    'n_sequences': _N_SYN, 'total_days': total_cat_days,
                    'cond_days': _COND_DAYS}, _f, indent=2)
    print(f"  Saved to {_RECOVERY_JSON}")
