    ('log10_d',   'log10_d',  'log10_d',     0.0,               ''),
    ('γ',         'gamma',     'gamma',       0.0,               ''),
    ('ρ',         'rho',       'rho',         0.0,               ''),
    # Identifiable combinations (RECAST-ETAS convention); not degenerate like k0/a/d/ρ
    ('α (derived)', 'alpha',   'alpha',       0.0,               '(a−ργ)/ln10'),
