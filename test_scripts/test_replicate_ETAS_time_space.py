# ─── Section 5: Fit RECAST's ETAS model — spatio-temporal NLL baseline ────────
#
# Before training RecurrentTPP we fit RECAST's built-in parametric ETAS model
# to the same training sequences.  This gives us:
#   (a) A BASELINE NLL that RecurrentTPP should eventually beat (or match).
#   (b) A PARAMETER RECOVERY check: do the fitted p, c, alpha, mu, d, gamma, rho
#       match the true values used in data generation?
#
# NLL COMPARABILITY:
#   Both models are scored as the likelihood of the observed events in the box W
#   over [0, T], per day and per km²:
#       ETAS:   −[Σ log λ(tᵢ,rᵢ) − ∫_W∫λ] / T
#       RECAST: −[Σ log f(τᵢ) + Σ log p_W(rᵢ|τᵢ,cᵢ) + log S(T − t_n)] / T
#   (time_weight = spatial_weight = 1; neither includes a magnitude term.)  This is
#   an exact equality of likelihoods when
#     - both spatial densities are per km² (RECAST's nll_loss applies the 1/(σx σy)
#       Jacobian),
#     - both are normalized over W: ETAS multiplies each parent's offspring integral
#       by the fraction of its kernel inside W and uses a uniform-on-rectangle
#       background (spatial_window); RECAST's mixture is renormalized by P(r ∈ W)
#       (window= argument of nll_loss, Monte Carlo).
#   The etas_2 generator discards events outside the polygon, so this is the process
#   that actually produced the data.

WINDOW = (-HALF_KM_LON, HALF_KM_LON, -HALF_KM_LAT, HALF_KM_LAT)   # km, box centred at 0

