def cond_seq_to_df(seq):
    """Convert a RECAST Sequence to an etas_2 auxiliary_catalog DataFrame.

    Converts fractional-day arrival times to datetimes relative to T_REF, and
    km offsets back to lat/lon using the box centroid and scale factors.
    """
    times = seq.arrival_times.numpy()
    lats  = seq.y_loc.numpy() / KM_PER_LAT + LAT_CTR
