# ── 4. Recovery table ─────────────────────────────────────────────────────────
# mu requires a gap correction: the inversion spreads mu over the full time
# window including inter-sequence buffers, but events only occur in active
# windows of length T_DAYS per sequence.
_gap_correction   = (float(T_DAYS) + _SEQ_GAP_DAYS) / float(T_DAYS)
_mu_correction_db = math.log10(_gap_correction)  # add to recovered log10_mu


def _with_derived(par):
    """Add the identifiable productivity combinations to an etas_2 parameter dict."""
    out = dict(par)
    out['alpha'] = (par['a'] - par['rho'] * par['gamma']) / math.log(10)
    out['k_rec'] = (10 ** par['log10_k0'] * math.pi / par['rho']
                    * (10 ** par['log10_d']) ** (-par['rho']))
    return out


_true_all = _with_derived(TRUE_PARAMS)
_rec_all  = _with_derived(_recovered)

_bounds = {
    'log10_mu': LOG10_MU_RANGE, 'log10_k0': LOG10_K0_RANGE, 'a': A_RANGE,
    'log10_c': LOG10_C_RANGE, 'omega': OMEGA_RANGE, 'log10_tau': LOG10_TAU_RANGE,
    'log10_d': LOG10_D_RANGE, 'gamma': GAMMA_RANGE, 'rho': RHO_RANGE,
}


def _at_bound(key, val, tol=0.02):
    """True if val lies within tol·(range width) of either etas_2 inversion bound."""
    if key not in _bounds or val is None:
        return False
    lo, hi = _bounds[key]
    return val <= lo + tol * (hi - lo) or val >= hi - tol * (hi - lo)


