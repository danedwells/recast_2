"""
test_replicate_ETAS.py
======================
Trains RECAST's RecurrentTPP on synthetic ETAS catalogs (generated by
generate_etas_synthetic.py) and evaluates how faithfully the neural model
replicates the generative process.

WHAT THIS TESTS:
    - Can a neural temporal point process (RecurrentTPP) recover the statistics
      of a known parametric model (ETAS)?
    - How much data does RecurrentTPP need before it matches ETAS's NLL on
      held-out sequences?  (Section 9: data quantity sweep)

WORKFLOW:
    1. Load etas_2 synthetic catalogs from parquet + metadata JSON.
    2. Project each catalog's lat/lon events into local km coordinates and
       build RECAST Sequence objects.
    3. Split into train / val / test (60 / 20 / 20).
    4. Fit RECAST's built-in ETAS model to training sequences — gives a
       parametric baseline NLL and a parameter recovery check.
    5. Train RecurrentTPP on the same sequences.
    6. Compare: NLL table, cumulative forecast bands, inter-event time mixture,
       spatial intensity map.
    7. Data quantity sweep: retrain with progressively fewer sequences to find
       the crossover point where RECAST beats ETAS.

PREREQUISITE:
    Run generate_etas_synthetic.py first to create:
        case_studies/etas2_synthetic/raw_catalogs.parquet
        case_studies/etas2_synthetic/true_params.json
"""

