# ─── Section 2: Load parquet and convert to RECAST Sequences ──────────────────
#
# etas_2 outputs a DataFrame with columns:
#     catalog_id, latitude [°N], longitude [°W], time [datetime], magnitude
#
# RECAST needs a Sequence object with:
#     inter_times  — time gaps between consecutive events [days]; shape (n+1,)
#                    inter_times[0]  = gap from window start (0.0) to first event
#                    inter_times[-1] = gap from last event to window end (T_DAYS)
#     t_start      — 0.0 (we define each window start as time zero)
#     mag          — ContinuousMarks object wrapping a (n,) float32 tensor
#     x_loc        — km east  of polygon centroid; shape (n,) float32
#     y_loc        — km north of polygon centroid; shape (n,) float32
#
# Coordinate projection:
#     x_km = (longitude − LON_CTR) × KM_PER_LON     east is positive
#     y_km = (latitude  − LAT_CTR) × KM_PER_LAT     north is positive
#
# This is the same flat-Earth (equirectangular) projection used in
# test_case_study.py:load_mainshock_sequence().  It's accurate to ~0.1% over
# the ~400 km extent of our box.

def catalog_to_sequence(df_group):
    """Convert one etas_2 catalog (a sub-DataFrame) to a RECAST Sequence.

    Args:
        df_group: DataFrame rows for a single catalog_id.
                  Expected columns: latitude, longitude, time, magnitude.

    Returns:
        eq.data.Sequence  with inter_times, mag (ContinuousMarks), x_loc, y_loc.
        None if the group has fewer than MIN_EVENTS events.
    """
    # Sort by time (etas_2 may not guarantee order when aftershock generations merge)
    df = df_group.sort_values("time").reset_index(drop=True)
    df = df[df.magnitude >= MC].reset_index(drop=True)

    if len(df) < MIN_EVENTS:
        return None

    # ── Project geographic coordinates to km offsets from the polygon centroid ─
    # "East" and "North" here match the convention in test_case_study.py so that
    # models trained on different datasets share the same spatial semantics.
    x_km = ((df.longitude.values - LON_CTR) * KM_PER_LON).astype(np.float32)
    y_km = ((df.latitude.values  - LAT_CTR) * KM_PER_LAT).astype(np.float32)

    # ── Convert datetime → fractional days since window start ─────────────────
    # Each catalog was generated over a T_DAYS-day window.  We measure time
    # from the window start (t_start = 0.0).  All etas_2 events fall strictly
    # in the open interval (0, T_DAYS), so the first and last inter-times are > 0.
    t_window_start = df["time"].iloc[0].replace(
        hour=0, minute=0, second=0, microsecond=0
    )
    # Round window start to nearest day boundary — etas_2 guarantees events are
    # in (window_start, window_end) so the exact value doesn't affect relative times.
    arrival_days = (df["time"] - t_window_start).dt.total_seconds().values / 86400.0
    # Safety clip: keep all arrivals strictly inside (0, T_DAYS) to avoid
    # zero or negative inter-times at floating-point boundaries.
    arrival_days = np.clip(arrival_days, 1e-6, T_DAYS - 1e-6)

    # inter_times[0]   = arrival_days[0] − 0.0          (gap from window start)
    # inter_times[i]   = arrival_days[i] − arrival_days[i-1]   (event to event)
    # inter_times[-1]  = T_DAYS − arrival_days[-1]       (gap to window end)
    inter_times = np.diff(arrival_days, prepend=[0.0], append=[float(T_DAYS)])

    # ── Wrap magnitudes in ContinuousMarks ─────────────────────────────────────
    # ContinuousMarks stores: the raw magnitude values + (mc, mag_max) bounds
    # used by RecurrentTPP to compute the Gutenberg-Richter log-probability.
    # The ETAS model ignores the bounds and reads only the raw .values tensor.
    mag = eq.data.ContinuousMarks(
        df.magnitude.values.astype(np.float32),
        bounds     = [MC, MAG_MAX],
        nll_bounds = [MC, MAG_MAX],
    )

    return eq.data.Sequence(
        inter_times,
        t_start = 0.0,     # all sequences start at t=0 (window start)
        mag     = mag,
        x_loc   = torch.tensor(x_km),
        y_loc   = torch.tensor(y_km),
    )


