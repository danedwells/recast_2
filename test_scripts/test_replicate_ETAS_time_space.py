#%%
# ─── Section 6: Define and train RecurrentTPP ─────────────────────────────────
#
# Architecture (from eq/models/recurrent.py):
#   Encoder: each event → [log(τ) − log(τ_mean), (x−x_mean)/x_std,
#                           (y−y_mean)/y_std, (m−Mc)]  — a 4-dimensional vector
#   RNN (GRU): encodes event history → context vector of size context_size
#   Decoders (hypernets):
#     hypernet_time → Weibull mixture parameters (num_components_time components)
#     hypernet_xy   → 2D Gaussian mixture parameters with Cholesky covariance
#     hypernet_mag  → Gutenberg-Richter parameters (effectively learns b-value)
#
# NLL loss returned per sequence per day:
#   − [log p(inter_times) + spatial_weight × log p(x_loc, y_loc) + log S(t_last)
#      − log S(t_first)]  /  (t_end − t_nll_start)
#
# time_weight = spatial_weight = 1 (constructor defaults), so the loss is a true
# likelihood; the spatial density is per km² (Jacobian applied in nll_loss).
#
# MODEL SIZE: We use a smaller model than test_case_study.py (context_size=64
# vs 256) because the synthetic sequences are shorter (30 vs 365 days) and
# the ETAS dynamics are simpler than real multi-sequence global seismicity.

model = eq.models.RecurrentTPP(
    context_size         = 64,    # RNN hidden-state dimension
    num_components_time  = 8,     # Weibull mixture components for time
    num_components_space = 16,    # mixture components for space
    tau_mean             = tau_mean,
    x_mean               = x_mean,
    y_mean               = y_mean,
    x_std                = x_std,
    y_std                = y_std,
    spatial_weight       = 1,
    spatial_dist          = SPATIAL_DIST,
    spatial_df            = SPATIAL_DF,
)
print(f"RecurrentTPP parameters: {sum(p.numel() for p in model.parameters()):,}")
print(f"Spatial component distribution: {SPATIAL_DIST}"
      + (f" (df={SPATIAL_DF})" if SPATIAL_DIST == "student_t" else ""))
