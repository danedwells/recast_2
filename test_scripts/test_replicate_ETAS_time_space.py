# ─── Section 14: Conditional intensity figure (paper Fig. 2 equivalent) ───────
# Three-panel figure matching Dascher-Cousineau et al. (2023) Figure 2:
#
#   A (top-left):    Magnitude scatter plot; right axis shows N(t) (observed
#                    cumulative count) alongside the ETAS and RECAST compensators
#                    Λ(t) = ∫₀ᵗ λ(s) ds.  A good model has Λ(t) ≈ N(t).
#
#   B (bottom-left): ETAS and RECAST conditional intensity λ(t) on a log scale.
#                    Panels A and B share the time axis.
#
#   C (right):       Histogram of per-catalog NLL differences
#                    log L̃_RECAST − log L̃_ETAS for every train and test sequence.
#                    Values > 0 mean ETAS preferred; < 0 mean RECAST preferred.
#
# ETAS intensity / compensator use the temporal marginal of the spatio-temporal
# model.  Because ∫∫ g(x,y|parent) dx dy = 1, the spatial kernel drops out and
# the temporal intensity reduces to the standard Omori sum — consistent with
# what etas_baseline.nll_loss() uses for the compensator internally.
# RECAST uses model.evaluate_intensity() and model.evaluate_compensator().

import matplotlib.gridspec as gridspec


def etas_temporal_intensity(seq, m, t_grid):
    """Marginal temporal intensity: λ(t) = μ + Σ_{j<t} k·10^{α(m_j−Mc)}·(t−t_j+c)^{−p}"""
    times = seq.arrival_times.numpy()
    mags  = seq.mag.numpy()
    p, c  = m.p.item(), m.c.item()
    prod  = m.k.item() * 10 ** (m.alpha.item() * (mags - m.M_c.item()))
    dt     = t_grid[:, None] - times[None, :]       # (T, n)
    causal = dt > 0
    omori  = np.where(causal, (np.maximum(dt, 0) + c) ** (-p), 0.0)
    return m.mu.item() + (prod * omori * causal).sum(axis=1)


def etas_temporal_compensator(seq, m, t_grid):
    """Compensator: Λ(t) = μ·t + Σ_{j<t} k·10^{α(m_j−Mc)}·[(t−t_j+c)^{1−p}−c^{1−p}]/(1−p)"""
    times = seq.arrival_times.numpy()
    mags  = seq.mag.numpy()
    p, c  = m.p.item(), m.c.item()
    prod  = m.k.item() * 10 ** (m.alpha.item() * (mags - m.M_c.item()))
    dt      = t_grid[:, None] - times[None, :]      # (T, n)
    causal  = dt > 0
    omori_i = np.where(causal,
                       ((np.maximum(dt, 0) + c) ** (1 - p) - c ** (1 - p)) / (1 - p),
                       0.0)
    return m.mu.item() * t_grid + (prod * omori_i).sum(axis=1)


