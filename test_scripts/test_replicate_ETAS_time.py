#%%
# ─── Section 5: True temporal ETAS — analytic baseline (no fitting) ───────────
#
# We compare RECAST directly against etas_2's TRUE generating temporal kernel
# (TRUE_PARAMS), not a re-fitted approximation via RECAST's own ETAS() class.
# Since these parameters generated the data, no inversion is needed.
#
# TWO UNIT PITFALLS THAT MUST MATCH etas_2's OWN CONVENTION EXACTLY
# (etas_2/etas/inversion.py:expected_aftershocks / triggering_kernel):
#
#   1. Productivity uses a NATURAL exponential, not base 10:
#          number_factor(m) = k0 · exp(a·(m − Mc))
#      RECAST's own classical ETAS() class instead uses 10**(alpha·Δm). An
#      earlier version of this script mistakenly plugged etas_2's `a` into
#      that base-10 formula, which inflates productivity by orders of
#      magnitude for any event above Mc (e.g. Δm=2.5: exp(1.69·2.5)≈72 vs.
#      10**(1.69·2.5)≈16,700) and produced a nonsensical mean NLL (~50+,
#      dominated by a few catastrophic outlier sequences with larger
#      mainshocks).
#
#   2. etas_2's spatial kernel is NOT normalized to integrate to 1 over the
#      plane. Marginalizing it out over all space contributes its own
#      magnitude-dependent factor:
#          area_factor(m) = (π / ρ) · (d · exp(γ·(m − Mc)))^(−ρ)
#      (same factor `expected_aftershocks()` uses). Dropping this factor
#      (as an earlier version did) silently changes the effective
#      productivity scale.
#
# The compensator below calls etas_2's own expected_aftershocks() directly
# (rather than re-deriving the incomplete-gamma taper integral by hand), so
# its normalization is guaranteed to match the generative model exactly. The
# instantaneous intensity uses the same number_factor/area_factor building
# blocks, just with the un-integrated kernel exp(−Δt/τ)·(Δt+c)^−(1+ω).

from etas.inversion import expected_aftershocks

TRUE_K0  = 10 ** TRUE_PARAMS["log10_k0"]    # base productivity [etas_2 units]
TRUE_TAU = 10 ** TRUE_PARAMS["log10_tau"]   # exponential taper scale [days]
TRUE_OMEGA = TRUE_PARAMS["omega"]           # Omori shape; p = 1 + omega

# theta order matches etas_2's own convention (etas/inversion.py:parameter_dict2array)
_THETA = (
    TRUE_PARAMS["log10_k0"], TRUE_ALPHA, TRUE_PARAMS["log10_c"], TRUE_OMEGA,
    TRUE_PARAMS["log10_tau"], TRUE_PARAMS["log10_d"], TRUE_GAMMA, TRUE_RHO,
)

print(f"\nTrue temporal ETAS parameters (etas_2 generating values, no fitting):")
print(f"  p={TRUE_P:.3f}  c={TRUE_C:.5f} d  k0={TRUE_K0:.5f}  a={TRUE_ALPHA:.3f}  "
      f"mu={TRUE_MU:.4f} events/day")


def _parent_coefficient(m):
    """number_factor(m) · area_factor(m): the combined magnitude-dependent
    coefficient in front of the (un-integrated) temporal kernel, after
    marginalizing etas_2's spatial kernel out over all space."""
    number_factor = TRUE_K0 * np.exp(TRUE_ALPHA * (m - MC))
    area_factor = np.pi / TRUE_RHO * (TRUE_D * np.exp(TRUE_GAMMA * (m - MC))) ** (-TRUE_RHO)
    return number_factor * area_factor


def etas_temporal_intensity(seq, mu, t_grid):
    """Temporal-marginal intensity: λ(t) = μ + Σ_{j<t} coef(m_j)·exp(−Δt/τ)·(Δt+c)^−(1+ω)"""
    times = seq.arrival_times.numpy()
    mags  = seq.mag.numpy()
    coef  = _parent_coefficient(mags)
    dt     = t_grid[:, None] - times[None, :]        # (T, n)
    causal = dt > 0
    dt_pos = np.maximum(dt, 0)
    kernel = np.exp(-dt_pos / TRUE_TAU) * (dt_pos + TRUE_C) ** -(1 + TRUE_OMEGA)
    return mu + (coef * kernel * causal).sum(axis=1)


def etas_temporal_compensator(seq, mu, t_grid):
    """Compensator: Λ(t) = μ·t + Σ_{j<t} expected_aftershocks(m_j; 0 → t−t_j).
    Delegates to etas_2's own expected_aftershocks() so the taper /
    incomplete-gamma normalization exactly matches the generative model."""
    times = seq.arrival_times.numpy()
    mags  = seq.mag.numpy()
    if len(times) == 0:
        return mu * t_grid
    dt = np.clip(t_grid[:, None] - times[None, :], 0.0, None)   # (T, n), non-causal → 0
    mags_b = np.broadcast_to(mags[None, :], dt.shape)
    contrib = expected_aftershocks([mags_b, np.zeros_like(dt), dt], [_THETA, MC])
    return mu * t_grid + contrib.sum(axis=1)


def true_etas_temporal_nll(seqs, mu=TRUE_MU):
    """Per-sequence temporal NLL per day, matching RecurrentTPP.nll_loss's definition:
        −[Σ log λ(t_i) − (Λ(t_end) − Λ(t_start))] / (t_end − t_start)
    Assumes t_start = 0 for every sequence (true for all catalogs built in Section 2).
    """
    nlls = []
    for seq in seqs:
        times = seq.arrival_times.numpy()
        log_lik = np.log(etas_temporal_intensity(seq, mu, times)).sum() \
            if len(times) > 0 else 0.0
        comp_end = etas_temporal_compensator(seq, mu, np.array([float(seq.t_end)]))[0]
        nlls.append(-(log_lik - comp_end) / (float(seq.t_end) - float(seq.t_start)))
    return np.array(nlls)


