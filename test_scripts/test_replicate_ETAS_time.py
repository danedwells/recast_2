"""
test_replicate_ETAS_time.py
============================
Trains RECAST's RecurrentTPP on synthetic ETAS catalogs (generated by
generate_etas_synthetic.py) and evaluates how faithfully the neural model
replicates the TEMPORAL component of the generative process, ignoring space.

WHAT THIS TESTS:
    - Can a neural temporal point process (RecurrentTPP) recover the inter-event
      time statistics of a known parametric model (ETAS), on its own?
    - How much data does RecurrentTPP need before it matches the true ETAS
      temporal NLL on held-out sequences?  (Section 13: data quantity sweep)

TIME-ONLY DESIGN:
    RecurrentTPP is instantiated with spatial_weight=0.0 (see
    eq/models/recurrent.py), so the spatial (x, y) term never contributes to
    the training loss — only the Weibull-mixture inter-event-time distribution
    is fit. x, y are still encoded as real observed RNN inputs during training
    (they carry signal about the true process), but sampled locations are not
    fed back into the RNN during generation, since the spatial decoder is
    never trained to produce anything meaningful.

    The comparison baseline is NOT a re-fitted RECAST ETAS() model. It is the
    TRUE analytic temporal ETAS kernel evaluated directly from TRUE_PARAMS
    (the parameters etas_2 used to generate the catalogs) — no inversion
    needed. Section 9's cumulative-count forecast additionally compares
    against etas_2's own simulate_catalog_continuation() output, reading off
    only the temporal marginal (event counts) and ignoring its spatial output.

WORKFLOW:
    1. Load etas_2 synthetic catalogs from parquet + metadata JSON.
    2. Project each catalog's lat/lon events into local km coordinates and
       build RECAST Sequence objects.
    3. Split into train / val / test (60 / 20 / 20).
    4. Derive the true analytic temporal ETAS kernel from TRUE_PARAMS (no
       fitting) — gives a parametric baseline NLL to compare against.
    5. Train RecurrentTPP (spatial_weight=0.0) on the same sequences.
    6. Compare: NLL table, cumulative forecast bands, inter-event time mixture,
       conditional intensity figure.
    7. Data quantity sweep: retrain with progressively fewer sequences to find
       the crossover point where RECAST beats the true ETAS temporal NLL.

PREREQUISITE:
    Run generate_etas_synthetic.py first to create:
        case_studies/etas2_synthetic/raw_catalogs.parquet
        case_studies/etas2_synthetic/true_params.json
"""

