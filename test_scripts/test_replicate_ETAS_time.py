    val_batch = eq.data.Batch.from_list(val_seqs).to(device)

    train_losses, val_losses = [], []
    model.train()
    for epoch in range(EPOCHS):
        epoch_losses = []
        for batch in train_loader:
            batch = batch.to(device)
            optimizer.zero_grad()
            nll = model.nll_loss(batch).mean()
            nll.backward()
            # Clip gradients to prevent parameter explosions (especially early on
            # when the context vectors are near-random and spatial NLL can spike).
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            epoch_losses.append(nll.item())

        # Validation NLL — computed without gradients on the full validation set.
        with torch.no_grad():
            v_nll = model.nll_loss(val_batch).mean().item()

        epoch_mean = float(np.mean(epoch_losses))
        train_losses.append(epoch_mean)
        val_losses.append(v_nll)
        scheduler.step()

        if (epoch + 1) % 25 == 0:
            print(f"Epoch {epoch+1:3d}  train={epoch_mean:.4f}  val={v_nll:.4f}")

    torch.save(model.state_dict(), f"{SAVE_DIR}/recast_etas2.pt")

    fig, ax = plt.subplots(figsize=(9, 3))
    ax.plot(train_losses, label='train', color='steelblue', lw=0.9)
    ax.plot(val_losses,   label='val',   color='orange',    lw=0.9)
    ax.axhline(etas_test_nll, ls='--', color='red', lw=1.2, label='ETAS temporal NLL')
    ax.set_xlabel("Epoch")
    ax.set_ylabel("Mean NLL / day")
    ax.set_title("RecurrentTPP training loss  (dashed = ETAS temporal baseline)")
    ax.legend()
    plt.tight_layout()
    plt.savefig(f"{FIGS_DIR}/recast_training_loss.png", dpi=150, bbox_inches='tight')
    plt.show()


