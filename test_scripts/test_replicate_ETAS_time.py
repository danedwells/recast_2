def cond_seq_to_df(seq):
    """Convert a RECAST Sequence to an etas_2 auxiliary_catalog DataFrame.

    Converts fractional-day arrival times to datetimes relative to T_REF, and
    km offsets back to lat/lon using the box centroid and scale factors.
    """
    times = seq.arrival_times.numpy()
    lats  = seq.y_loc.numpy() / KM_PER_LAT + LAT_CTR
    lons  = seq.x_loc.numpy() / KM_PER_LON + LON_CTR
    mags  = seq.mag.numpy()
    return pd.DataFrame({
        'latitude':  lats,
        'longitude': lons,
        'time':      [T_REF + dt.timedelta(days=float(t)) for t in times],
        'magnitude': mags,
        'xi_plus_1': 1.0,
    })


def forecast_cumulative(batch, t_cut, t_grid):
    """Cumulative event count relative to t_cut for each sampled RECAST trajectory.

    Args:
        batch  : Batch returned by model.sample().
        t_cut  : Conditioning cutoff time (fractional days).
        t_grid : 1-D array of relative times at which to evaluate the count.

    Returns:
        cum: int array of shape (batch_size, len(t_grid)).
    """
    cum = np.zeros((batch.batch_size, len(t_grid)), dtype=int)
    for i in range(batch.batch_size):
        n        = int(batch.end_idx[i])
        times    = batch.arrival_times[i, :n].numpy()
        fore_rel = np.sort(times[times > t_cut] - t_cut)
        cum[i]   = np.searchsorted(fore_rel, t_grid, side='right')
    return cum


